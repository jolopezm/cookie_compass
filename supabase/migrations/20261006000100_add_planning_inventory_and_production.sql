do $$
declare
  v_table text;
  v_policy record;
begin
  foreach v_table in array array[
    'clientes', 'productos', 'ordenes', 'detalle_ordenes',
    'planes_cliente_producto', 'materias_primas', 'recetas', 'detalle_recetas',
    'egresos', 'detalle_compras', 'producciones', 'consumos_produccion',
    'movimientos_inventario'
  ]
  loop
    execute format('alter table public.%I enable row level security', v_table);
    for v_policy in
      select policyname
      from pg_policies
      where schemaname = 'public' and tablename = v_table
    loop
      execute format('drop policy %I on public.%I', v_policy.policyname, v_table);
    end loop;
    execute format(
      'create policy cookie_compass_authenticated_access on public.%I for all to authenticated using (public.es_usuario_cookie_compass()) with check (public.es_usuario_cookie_compass())',
      v_table
    );
  end loop;
end;
$$;

